  pick(cats, maxCh, n, exclude){
    let pool = QUIZ_BANK.filter(q=>
      (!cats || cats.includes(q.cat)) && q.ch<=(maxCh||5) && !(exclude&&exclude.includes(q.q))
    );
    /* 不足则放宽章序 */
    if(pool.length<n) pool = QUIZ_BANK.filter(q=>(!cats||cats.includes(q.cat))&&!(exclude&&exclude.includes(q.q)));
    for(let i=pool.length-1;i>0;i--){ const j=Math.floor(Math.random()*(i+1)); [pool[i],pool[j]]=[pool[j],pool[i]]; }
    return pool.slice(0, n).map(q=>({q:q.q, opts:q.opts.slice(), a:q.a, why:q.why}));
  },

  /** 喜好题（动态）：某神最钟爱/忌讳的供品 */
