    const lovedId=g.gifts.loved[0];
    const right=ITEMS[lovedId]?ITEMS[lovedId].name:lovedId;
    /* 干扰项：从其它礼物里取，且不与该神 liked/disliked 重合 */
    const own=new Set([...(g.gifts.loved||[]),...(g.gifts.liked||[]),...(g.gifts.disliked||[])]);
    const others=Object.keys(ITEMS).filter(id=>ITEMS[id].slot==='gift' && !own.has(id));
